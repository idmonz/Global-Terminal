def main() -> int:
    for module in MODULES:
        importlib.import_module(module)
        print(f"import ok: {module}")
    from lib.equity_breadth import load_sp500_universe
    from lib.oil_flows import build_chokepoint_registry
    from lib.stress_tests import build_stress_test_matrix

    universe, universe_status = load_sp500_universe()
    assert not universe.empty, "S&P universe seed is empty"
    assert "ticker" in universe.columns, "S&P universe missing ticker"
    assert len(build_chokepoint_registry()) >= 8, "chokepoint registry incomplete"
    stress, stress_status = build_stress_test_matrix(["SPY", "TLT"])
    assert len(stress) == 7, "stress matrix incomplete"
    assert stress_status.ok, "stress status not ok"
    print("smoke checks passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
